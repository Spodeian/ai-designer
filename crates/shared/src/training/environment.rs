//! Training Environment Management & Turnkey Workspace Generator.
//! Emits production launch scripts (setup_env.sh/ps1, run_training.sh/ps1),
//! virtualenv setup files (uv/pip/conda), runtime configs, and model harnesses.

use crate::codegen::pytorch_gen::generate_pytorch_project;
use crate::spec::AiDesignSpec;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fs;
use std::path::Path;

/// Manifest describing the created turnkey training environment.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TrainingEnvironmentManifest {
    pub model_id: String,
    pub target_dir: String,
    pub created_files: Vec<String>,
    pub python_version_req: String,
    pub torch_version_req: String,
    pub has_cuda_support: bool,
    pub recommended_launch_command: String,
    pub total_parameters: usize,
    pub estimated_vram_gb: f64,
}

/// Generates all scripts, configs, and training files for a turnkey execution environment.
pub fn generate_environment_bundle(spec: &AiDesignSpec) -> HashMap<String, String> {
    // 1. Core PyTorch project files (model.py, train.py, losses.py, data.py, requirements.txt)
    let mut files = generate_pytorch_project(spec);

    let model_id = &spec.metadata.model_id;

    // 2. Conda / Mamba environment.yml
    files.insert(
        "environment.yml".to_string(),
        format!(
            r#"name: aid_{model_id}
channels:
  - pytorch
  - nvidia
  - conda-forge
dependencies:
  - python>=3.11
  - pytorch>=2.4.0
  - torchvision
  - torchaudio
  - pytorch-cuda=12.4
  - pip:
      - safetensors>=0.4.3
      - numpy>=1.26.0
      - triton>=3.0.0; sys_platform == 'linux'
      - rich>=13.7.0
"#
        ),
    );

    // 3. Modern pyproject.toml for uv
    files.insert(
        "pyproject.toml".to_string(),
        format!(
            r#"[project]
name = "aid-training-{model_id}"
version = "0.1.0"
description = "Turnkey training harness for {model_id} generated by AI Designer"
readme = "README.md"
requires-python = ">=3.11"
dependencies = [
    "torch>=2.4.0",
    "safetensors>=0.4.3",
    "numpy>=1.26.0",
    "rich>=13.7.0",
]

[tool.uv]
dev-dependencies = [
    "pytest>=8.0.0",
]
"#
        ),
    );

    // 4. POSIX setup_env.sh
    files.insert(
        "setup_env.sh".to_string(),
        format!(
            r#"#!/usr/bin/env bash
# Turnkey Python Environment Setup for {model_id}
set -euo pipefail

echo "================================================================="
echo " AI Designer Studio — Turnkey Training Environment Setup"
echo " Model ID: {model_id}"
echo "================================================================="

# 1. Prefer uv for fast virtualenv creation, otherwise python3 -m venv
if command -v uv >/dev/null 2>&1; then
    echo "[+] Using 'uv' for ultra-fast virtualenv creation..."
    uv venv .venv
    source .venv/bin/activate
    uv pip install -r requirements.txt
else
    echo "[+] 'uv' not found; falling back to python3 -m venv..."
    python3 -m venv .venv
    source .venv/bin/activate
    python3 -m pip install --upgrade pip
    pip install -r requirements.txt
fi

echo "[+] Verifying PyTorch hardware acceleration..."
python3 -c "import torch; print(f'  PyTorch: {{torch.__version__}} | CUDA: {{torch.cuda.is_available()}} | Device: {{torch.cuda.get_device_name(0) if torch.cuda.is_available() else \"CPU\"}}')"

echo "================================================================="
echo " Environment setup complete!"
echo "   Activate: source .venv/bin/activate"
echo "   Train   : python train.py"
echo "================================================================="
"#
        ),
    );

    // 5. Windows setup_env.ps1
    files.insert(
        "setup_env.ps1".to_string(),
        format!(
            r#"# Turnkey Python Environment Setup for {model_id}
$ErrorActionPreference = "Stop"

Write-Host "=================================================================" -ForegroundColor Cyan
Write-Host " AI Designer Studio — Turnkey Training Environment Setup" -ForegroundColor Cyan
Write-Host " Model ID: {model_id}" -ForegroundColor Cyan
Write-Host "=================================================================" -ForegroundColor Cyan

if (Get-Command uv -ErrorAction SilentlyContinue) {{
    Write-Host "[+] Using 'uv' for virtualenv creation..." -ForegroundColor Green
    uv venv .venv
    & .\.venv\Scripts\Activate.ps1
    uv pip install -r requirements.txt
}} else {{
    Write-Host "[+] Using python -m venv..." -ForegroundColor Green
    python -m venv .venv
    & .\.venv\Scripts\Activate.ps1
    python -m pip install --upgrade pip
    python -m pip install -r requirements.txt
}}

Write-Host "[+] Verifying PyTorch hardware acceleration..." -ForegroundColor Yellow
python -c "import torch; print(f'  PyTorch: {{torch.__version__}} | CUDA: {{torch.cuda.is_available()}} | Device: {{torch.cuda.get_device_name(0) if torch.cuda.is_available() else \"CPU\"}}')"

Write-Host "=================================================================" -ForegroundColor Cyan
Write-Host " Environment setup complete!" -ForegroundColor Cyan
Write-Host "   Activate: .\.venv\Scripts\Activate.ps1" -ForegroundColor Cyan
Write-Host "   Train   : python train.py" -ForegroundColor Cyan
Write-Host "=================================================================" -ForegroundColor Cyan
"#
        ),
    );

    // 6. POSIX run_training.sh
    files.insert(
        "run_training.sh".to_string(),
        format!(
            r#"#!/usr/bin/env bash
set -euo pipefail
if [ -d ".venv" ]; then
    source .venv/bin/activate
fi
echo "[+] Starting training run for {model_id}..."
python train.py "$@"
"#
        ),
    );

    // 7. Windows run_training.ps1
    files.insert(
        "run_training.ps1".to_string(),
        format!(
            r#"if (Test-Path ".\.venv\Scripts\Activate.ps1") {{
    & .\.venv\Scripts\Activate.ps1
}}
Write-Host "[+] Starting training run for {model_id}..." -ForegroundColor Green
python train.py @args
"#
        ),
    );

    // 8. Runtime training_config.json
    let config_json = serde_json::to_string_pretty(&spec.training).unwrap_or_default();
    files.insert("training_config.json".to_string(), config_json);

    // 9. README.md
    files.insert(
        "README.md".to_string(),
        format!(
            r#"# AI Designer Training Environment: {model_id}

Auto-generated turnkey training workspace for **{model_id}** (`{}`).

## 1. Setup Environment
```bash
# On Linux / macOS:
bash setup_env.sh

# On Windows (PowerShell):
.\setup_env.ps1
```

## 2. Launch Training
```bash
# On Linux / macOS:
./run_training.sh

# On Windows:
.\run_training.ps1
```

## 3. Directory Layout
- `model.py` — Auto-generated PyTorch model definition (`nn.Module`).
- `train.py` — Multi-stage training loop with optimizer partitioning (Muon + AdamW).
- `losses.py` — Configured loss functions and regularizers.
- `data.py` — Synthetic and streaming DataLoader templates.
- `training_config.json` — Hyperparameters, schedules, and parallelism topology.
- `requirements.txt` — Python dependencies.
"#,
            spec.metadata.display_name
        ),
    );

    files
}

/// Creates a complete training environment workspace on disk at `target_dir`.
pub fn setup_training_environment(
    spec: &AiDesignSpec,
    target_dir: &Path,
) -> Result<TrainingEnvironmentManifest, String> {
    fs::create_dir_all(target_dir)
        .map_err(|e| format!("Failed to create directory {}: {}", target_dir.display(), e))?;

    let bundle = generate_environment_bundle(spec);
    let mut created_files = Vec::new();

    for (rel_path, content) in &bundle {
        let dest = target_dir.join(rel_path);
        if let Some(parent) = dest.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("Failed to create parent dir: {}", e))?;
        }
        fs::write(&dest, content)
            .map_err(|e| format!("Failed to write {}: {}", dest.display(), e))?;
        created_files.push(rel_path.clone());
    }

    created_files.sort();

    let partition = crate::analysis::partition_parameters(spec);
    let roofline = crate::analysis::analyze_roofline(spec, 4, 1024);

    let launch_cmd = if cfg!(windows) {
        "powershell -ExecutionPolicy Bypass -File .\\run_training.ps1".to_string()
    } else {
        "./run_training.sh".to_string()
    };

    Ok(TrainingEnvironmentManifest {
        model_id: spec.metadata.model_id.clone(),
        target_dir: target_dir.to_string_lossy().to_string(),
        created_files,
        python_version_req: ">=3.11".to_string(),
        torch_version_req: ">=2.4.0".to_string(),
        has_cuda_support: roofline.hardware_profile.contains("NVIDIA")
            || roofline.hardware_profile.contains("CUDA"),
        recommended_launch_command: launch_cmd,
        total_parameters: partition.total_param_count,
        estimated_vram_gb: roofline.vram.total_allocated_bytes as f64 / 1e9,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scaffold_archetype;
    use crate::spec::ArchitectureArchetype;

    #[test]
    fn test_generate_environment_bundle() {
        let spec = scaffold_archetype(
            ArchitectureArchetype::GenerativeLLM,
            "test_llm",
            "Test LLM",
            256,
            2,
            crate::spec::PrecisionFormat::BF16,
        );
        let bundle = generate_environment_bundle(&spec);

        assert!(bundle.contains_key("setup_env.sh"));
        assert!(bundle.contains_key("setup_env.ps1"));
        assert!(bundle.contains_key("run_training.sh"));
        assert!(bundle.contains_key("run_training.ps1"));
        assert!(bundle.contains_key("environment.yml"));
        assert!(bundle.contains_key("pyproject.toml"));
        assert!(bundle.contains_key("training_config.json"));
        assert!(bundle.contains_key("train.py"));
        assert!(bundle.contains_key("model.py"));
        assert!(bundle.contains_key("requirements.txt"));

        let env_yml = bundle.get("environment.yml").unwrap();
        assert!(env_yml.contains("pytorch>=2.4.0"));
        let pyproject = bundle.get("pyproject.toml").unwrap();
        assert!(pyproject.contains("[project]"));
    }

    #[test]
    fn test_setup_training_environment_on_disk() {
        let spec = scaffold_archetype(
            ArchitectureArchetype::VisionDiffusion,
            "test_dit",
            "Test DiT",
            256,
            2,
            crate::spec::PrecisionFormat::FP16,
        );
        let tmp_dir = std::env::temp_dir().join("test_aid_env_setup");
        let _ = fs::remove_dir_all(&tmp_dir);

        let manifest =
            setup_training_environment(&spec, &tmp_dir).expect("Environment setup failed");
        assert_eq!(manifest.model_id, spec.metadata.model_id);
        assert!(!manifest.created_files.is_empty());
        assert!(tmp_dir.join("train.py").exists());
        assert!(tmp_dir.join("run_training.sh").exists());

        let _ = fs::remove_dir_all(&tmp_dir);
    }
}
