/// Generates a complete, self-contained PyTorch 2 project directory file map.
pub fn generate_pytorch_project(spec: &AiDesignSpec) -> HashMap<String, String> {
    let mut files = HashMap::new();

    files.insert("model.py".to_string(), generate_model_py(spec));
    files.insert("train.py".to_string(), generate_train_py(spec));
    files.insert("losses.py".to_string(), generate_losses_py(spec));
    files.insert("data.py".to_string(), generate_data_py(spec));
    files.insert(
        "requirements.txt".to_string(),
        generate_requirements_txt(spec),
    );

    files
}

